package com.zoneu.app.agent

/**
 * 两条「最后一条 system」指令：续写与替我写。
 *
 * 为什么写成 system 而不是插一条用户消息：插进去的那句话会落库，下一轮模型会以为用户真的说过
 * 「接着写」；而且它会出现在界面上，把一段好好的对话变成自言自语。system 只活在这一轮请求里。
 *
 * 措辞上反复强调「不要重复 / 不要重新开场 / 不要总结」，是因为这几种跑偏在实测里最常见：
 * 只说「继续」，模型有相当比例会重写上一段，或者来一句「好的，我们继续」把气氛打断。
 */
object TavernDirectives {
  /** 续写：接着上一条助手消息往下写，正文追加到同一条里。 */
  const val CONTINUE: String =
    "（续写）接着上一条助手消息的最后一句往下写，只补新的内容。" +
      "不要重复已经写过的句子，不要重新开场或重新打招呼，不要总结，不要加解释、标题或括号说明。" +
      "直接输出接下来的正文。"

  /** 替我写：让模型站在用户这边写一句，结果只填进输入框，不自动发送。 */
  const val IMPERSONATE: String =
    "（替我写）以用户的口吻写下一句发言，符合此前的称呼、语气与当前处境。" +
      "只输出这一句话本身：不要旁白，不要动作描写，不要解释，不要引号，不要重复对方的台词。"

  /**
   * 把模型回来的那一行收拾成「能直接填进输入框」的样子。
   *
   * 明明说了不要引号，实测仍有相当比例会包一层 `“……”` 或者加个 `用户：` 前缀。
   * 这些不是模型不听话，而是训练数据里「替人写台词」几乎总是带引号 —— 与其在指令里死磕，
   * 不如在这里剥掉。剥的只是**首尾包裹**，句子中间的引号是内容，不能动。
   */
  fun asUserLine(raw: String): String {
    var line = raw.trim().removePrefix("用户：").removePrefix("用户:").trim()
    // 用 Char 而不是 String 配对：ASCII 双引号写成字符串要转义，转义在工具链里一抖就变成空串
    // （第一次编译就是这么坏的：listOf("" to "", ...) 看着完全正常，却谁也不剥）。
    listOf('"' to '"', '“' to '”', '「' to '」').forEach { (open, close) ->
      if (line.length > 1 && line.first() == open && line.last() == close) {
        line = line.substring(1, line.length - 1).trim()
      }
    }
    return line.trim().trim('*').trim()
  }
}
